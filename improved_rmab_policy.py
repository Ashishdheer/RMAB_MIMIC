import numpy as np

def evaluate_policy_DR(
    config,
    b_all,
    q_all,
    all_actions,
    all_rewards,
    seq_starts,
    seq_lens,
    gamma=0.95,
):
    alpha = config['alpha']
    tau   = config['tau']
    temp  = config['temp']
    clip  = config.get('clip', 2.5)

    total_T, K = b_all.shape

    # -------------------------
    # 1) Target Policy π
    # -------------------------
    logits = q_all / (temp + 1e-12)
    pi = np.exp(logits - logits.max(axis=1, keepdims=True))
    pi /= (pi.sum(axis=1, keepdims=True) + 1e-12)

    if tau > 0:
        mask = (b_all < tau)
        pi = np.where(mask, 0.0, pi)
        s = pi.sum(axis=1, keepdims=True)
        pi = np.where(s > 0, pi/(s+1e-12), b_all)

    pi_mix = (1 - alpha)*b_all + alpha*pi

    # -------------------------
    # 2) Per-step ratios
    # -------------------------
    idx = np.arange(total_T)
    b_sel  = np.maximum(b_all[idx, all_actions], 1e-12)
    pi_sel = np.maximum(pi_mix[idx, all_actions], 1e-12)

    ratio = pi_sel / b_sel
    ratio = np.minimum(ratio, clip)

    # -------------------------
    # 3) Precompute V(s)
    # -------------------------
    V_s = np.sum(pi_mix * q_all, axis=1)

    # -------------------------
    # 4) Per-trajectory loop
    # -------------------------
    n_seq = len(seq_lens)
    WIS_vals = np.zeros(n_seq)
    DR_vals  = np.zeros(n_seq)
    BEHAV_vals = np.zeros(n_seq)

    ptr = 0
    for i in range(n_seq):
        L = seq_lens[i]

        rho_cum = 1.0
        rho_prev = 1.0
        wis_return = 0.0
        dr_return  = 0.0
        beh_return = 0.0

        for t in range(L):
            r = all_rewards[ptr+t]
            discount = gamma**t

            # Behavior return
            beh_return += discount * r

            # WIS
            rho_cum *= ratio[ptr+t]
            wis_return += discount * rho_cum * r

            # DR
            Q_sa = q_all[ptr+t, all_actions[ptr+t]]

            dr_return += discount * (
                rho_cum * (r - Q_sa)
                + rho_prev * V_s[ptr+t]
            )

            rho_prev = rho_cum

        WIS_vals[i] = wis_return
        DR_vals[i]  = dr_return
        BEHAV_vals[i] = beh_return

        ptr += L


    behavior_value = BEHAV_vals.mean()

    W = np.ones_like(WIS_vals)
    wis_value = WIS_vals.mean()

    dr_value = DR_vals.mean()



    ptr = 0
    traj_weights = np.zeros(n_seq)
    for i in range(n_seq):
        L = seq_lens[i]
        traj_weights[i] = np.prod(ratio[ptr:ptr+L])
        ptr += L

    ess = (traj_weights.sum()**2) / (np.sum(traj_weights**2) + 1e-12)

    return {
        "behavior": behavior_value,
        "wis": wis_value,
        "dr": dr_value,
        "ess": ess,
        "traj_weights": traj_weights,
        "WIS_vals": WIS_vals,
        "DR_vals": DR_vals
    }

