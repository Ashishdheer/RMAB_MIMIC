import numpy as np

def compute_wis_ess_vectorized(config, b_all, q_all, all_actions, seq_starts, seq_lens, gamma=0.95, clip=3.0):
    # config = {'alpha':..., 'tau':..., 'temp':...}
    alpha, tau, temp = config['alpha'], config['tau'], config['temp']
    # 1) compute pi (softmax across actions) from q_all / temp
    logits = q_all / (temp + 1e-12)
    pi = np.exp(logits - logits.max(axis=1, keepdims=True))
    pi = pi / (pi.sum(axis=1, keepdims=True) + 1e-12)   # (total_T, K)

    # 2) apply tau truncation: where b_all < tau, zero out pi and renormalize to b if zero
    if tau > 0:
        mask = (b_all < tau)       # boolean (total_T, K)
        # set pi to zero where mask True, but mask is per-action; we only want to zero actions whose b < tau
        pi = np.where(mask, 0.0, pi)
        s = pi.sum(axis=1, keepdims=True)
        # where s==0, fallback to b_all
        pi = np.where(s > 0, pi / (s + 1e-12), b_all)

    # 3) mix with behavior
    pi_mix = (1.0 - alpha) * b_all + alpha * pi

    # 4) select probabilities for executed actions
    idx = np.arange(all_actions.shape[0])
    b_sel = np.maximum(b_all[idx, all_actions], 1e-12)
    pi_sel = np.maximum(pi_mix[idx, all_actions], 1e-12)

    # 5) optional clipping: clip ratio to [1/clip, clip] if symmetric desired; original used upper clip
    ratio = pi_sel / b_sel
    ratio = np.minimum(ratio, clip)   # keep lower bound ~0
    log_ratio = np.log(ratio + 1e-12)

    # 6) sum log_ratio per-trajectory into logW for each trajectory
    # Use add.reduceat with seq_starts
    # create array of cumulative sums per timestep weight to split by seq_starts
    cumsum_logratio = np.add.reduceat(log_ratio, seq_starts)  # sum of log_ratios per seq
    # But add.reduceat with seq_starts expects proper indexing; ensure indexing covers all sequences
    # For safety, compute per-trajectory using loop over starts if this errors; but it's usually fast.

    # convert to W (exp)
    W = np.exp(cumsum_logratio)

    # 7) compute returns per trajectory fast (discounted)
    # Precompute prefix sums of discounted returns across flat array then reduceat
    # But easier: compute per-timestep discounted reward-to-go per trajectory is more work.
    # Simpler (vectorized): iterate per trajectory lengths but that's cheap compared to model predicts.
    # However, we can compute return-per-trajectory by grouping using the seq_starts/seq_lens:
    n_seq = len(seq_lens)
    Rv = np.empty(n_seq, dtype=float)
    ptr = 0
    for i in range(n_seq):
        L = seq_lens[i]
        r = all_rewards[ptr:ptr+L]
        discounts = (gamma ** np.arange(L))
        Rv[i] = (discounts * r).sum()
        ptr += L

    # 8) WIS and ESS
    W = np.clip(W, 0.0, 1e12)
    wis = float((W * Rv).sum() / (W.sum() + 1e-12))
    ess = float((W.sum()**2) / (np.sum(W**2) + 1e-12))
    return {'W': W, 'R': Rv, 'wis': wis, 'ess': ess}

