def compute_wis_ess_for_seqdict(seq_dict, bundle, cfg, gamma=0.95):
    behavior = bundle["models"]["behavior"]
    q_models = bundle["models"]["q_models"]
    state_cols = bundle["state_cols"]
    actions = sorted(list(q_models.keys()))
    weights, returns = [], []
    for _, seq in seq_dict.items():
        S, A, R = np.asarray(seq["S"]), np.asarray(seq["A"], int), np.asarray(seq["R"], float)
        X = pd.DataFrame(S, columns=state_cols).fillna(0.0)
        b = behavior.predict_proba(X)                    # (T,K)
        q = np.vstack([q_models[a].predict(X.values) for a in actions]).T
        pi = softmax(q / cfg["temp"], axis=1)
        if cfg.get("tau", 0.0) > 0:
            mask = b < cfg["tau"]
            pi = np.where(mask, 0.0, pi)
            s = pi.sum(1, keepdims=True)
            pi = np.where(s > 0, pi/s, b)
        pi_mix = (1.0 - cfg["alpha"]) * b + cfg["alpha"] * pi
        idx = np.arange(len(A))
        b_sel = np.maximum(b[idx, A], 1e-12)
        pi_sel = np.maximum(pi_mix[idx, A], 1e-12)
        ratio = np.clip(pi_sel / b_sel, 0.0, cfg.get("clip", 3.0))
        w = float(np.prod(ratio))
        ret = float((gamma ** np.arange(len(R)) * R).sum())
        weights.append(w); returns.append(ret)
    W = np.array(weights, dtype=float); Rv = np.array(returns, dtype=float)
    wis = float((W * Rv).sum() / (W.sum() + 1e-12))
    ess = float((W.sum()**2) / (np.sum(W**2) + 1e-12)) if W.size>0 else 0.0
    behavior_value = float(Rv.mean())
    return {"W":W, "R":Rv, "wis":wis, "ess":ess, "behavior":behavior_value}

def bootstrap_ci(W, Rv, B=1000, seed=42):
    rng = np.random.default_rng(seed)
    n = len(W)
    vals = np.empty(B)
    for i in range(B):
        idx = rng.integers(0, n, n)
        w_s = W[idx]; r_s = Rv[idx]
        vals[i] = (w_s * r_s).sum() / (w_s.sum() + 1e-12)
    return np.percentile(vals, [2.5, 97.5]), vals

