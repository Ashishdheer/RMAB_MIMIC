def bootstrap_group(values, mask, B=500):
    rng = np.random.default_rng(0)
    group_vals = values[mask]
    n = len(group_vals)
    samples = []
    for _ in range(B):
        idx = rng.integers(0, n, n)
        samples.append(group_vals[idx].mean())
    return np.percentile(samples, [2.5, 97.5])

